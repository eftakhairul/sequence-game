/**
 * One-off generator for the board layout constant (spec §4.2).
 *
 *   pnpm generate-board
 *
 * Seeded shuffle with seed 0x4C494E45 (expanded to a 4-word xoshiro128** state with splitmix32);
 * retries with seed+1 until the two copies of every card are never in the same row, never in the
 * same column and never 8-neighbour adjacent. Writes packages/rules/src/boardLayout.ts.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BOARD_CARDS } from '../packages/rules/src/cards.js';
import { createRng, seedFromNumber, shuffleInPlace } from '../packages/rules/src/rng.js';
import type { Card } from '../packages/rules/src/types.js';

const BASE_SEED = 0x4c494e45;
const CORNERS = new Set([0, 9, 90, 99]);

export function layoutOk(layout: readonly (Card | null)[]): boolean {
  const seen = new Map<Card, number>();
  for (let i = 0; i < 100; i++) {
    const card = layout[i];
    if (card === null || card === undefined) continue;
    const other = seen.get(card);
    if (other === undefined) {
      seen.set(card, i);
      continue;
    }
    const r1 = Math.floor(other / 10);
    const c1 = other % 10;
    const r2 = Math.floor(i / 10);
    const c2 = i % 10;
    if (r1 === r2 || c1 === c2) return false;
    if (Math.abs(r1 - r2) <= 1 && Math.abs(c1 - c2) <= 1) return false;
  }
  return true;
}

export function generate(): { seed: number; layout: (Card | null)[]; attempts: number } {
  for (let attempt = 0; ; attempt++) {
    const seed = (BASE_SEED + attempt) >>> 0;
    const rng = createRng(seedFromNumber(seed));
    const cards = shuffleInPlace(rng, [...BOARD_CARDS, ...BOARD_CARDS]);
    const layout: (Card | null)[] = [];
    let k = 0;
    for (let i = 0; i < 100; i++) layout.push(CORNERS.has(i) ? null : (cards[k++] as Card));
    if (layoutOk(layout)) return { seed, layout, attempts: attempt + 1 };
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { seed, layout, attempts } = generate();
  const rows: string[] = [];
  for (let r = 0; r < 10; r++) {
    rows.push(
      '  ' +
        layout
          .slice(r * 10, r * 10 + 10)
          .map((c) => (c === null ? 'null' : `'${c}'`))
          .join(', ') +
        ',',
    );
  }
  const out = `// AUTO-GENERATED by scripts/generate-board.ts — do not edit by hand.
// Base seed 0x4C494E45; accepted seed below (found after ${attempts} attempt(s)).
import type { Card } from './types.js';

export const BOARD_SEED = 0x${seed.toString(16).toUpperCase()};

export const BOARD_LAYOUT: readonly (Card | null)[] = [
${rows.join('\n')}
];
`;
  const target = fileURLToPath(new URL('../packages/rules/src/boardLayout.ts', import.meta.url));
  writeFileSync(target, out);
  console.log(`Wrote ${target} (seed 0x${seed.toString(16)}, ${attempts} attempts)`);
}
